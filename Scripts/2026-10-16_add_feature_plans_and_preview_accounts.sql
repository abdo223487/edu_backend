-- باقات الفيتشرز + حسابات المعاينة.
--  * FeaturePlans            : the plans the SuperAdmin creates (name, price, features)
--  * Teachers.PlanId         : plan a teacher is on (NULL = custom / none)
--  * Teachers.ClosedAt       : PREVIEW accounts - closed / already converted
--  * Teachers.ConvertedTeacherId : PREVIEW accounts - the real teacher it became
--
-- Requires 2026-10-16_add_teacher_disabled_features.sql (or its migration) first.
-- Safe to run multiple times. Matches the AddFeaturePlansAndPreviewAccounts
-- migration exactly -- run ONE of the two against a given database, never both.

CREATE TABLE IF NOT EXISTS "FeaturePlans" (
    "Id"            integer GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    "Name"          text NOT NULL,
    "Price"         numeric(18,2) NOT NULL,
    "FeatureKeys"   text NULL,
    "ExtraIncluded" text NULL,
    "ExtraExcluded" text NULL,
    "CreatedAt"     timestamp with time zone NOT NULL
);

ALTER TABLE "Teachers" ADD COLUMN IF NOT EXISTS "PlanId" integer NULL;
ALTER TABLE "Teachers" ADD COLUMN IF NOT EXISTS "ClosedAt" timestamp with time zone NULL;
ALTER TABLE "Teachers" ADD COLUMN IF NOT EXISTS "ConvertedTeacherId" integer NULL;

CREATE INDEX IF NOT EXISTS "IX_Teachers_PlanId" ON "Teachers" ("PlanId");
